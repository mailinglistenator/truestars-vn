function t(key, lang = currentLang, params = {}) {
  const dict = I18N[lang] || I18N["en"] || {};
  let str = dict[key] || (I18N["en"] && I18N["en"][key]) || key;
  for (const [k, v] of Object.entries(params)) {
    str = str.replace(new RegExp(`\\{${k}\\}`, "g"), v);
  }
  return str;
}

function setLanguage(lang) {
  if (!I18N[lang]) lang = "en";
  currentLang = lang;
  try {
    localStorage.setItem("truestars_lang", lang);
  } catch (e) {}

  document.querySelectorAll(".lang-btn").forEach(btn => {
    btn.classList.toggle("active", btn.dataset.lang === lang);
  });

  const dict = I18N[lang];
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (dict[key]) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (dict[key]) {
      el.placeholder = dict[key];
    }
  });

  // Re-translate dynamic badges and active audit verdict if active
  if (typeof refreshAuditVerdictI18n === "function") {
    refreshAuditVerdictI18n(lang);
  }
}

function initLanguage() {
  let saved = "en";
  try {
    saved = localStorage.getItem("truestars_lang") || "";
  } catch (e) {}

  if (!saved && typeof navigator !== "undefined" && navigator.language) {
    const nav = navigator.language.toLowerCase();
    if (nav.startsWith("vi")) saved = "vi";
    else if (nav.startsWith("zh")) saved = "zh";
    else if (nav.startsWith("ko")) saved = "ko";
    else if (nav.startsWith("ja")) saved = "ja";
    else if (nav.startsWith("es")) saved = "es";
  }

  if (!saved || !I18N[saved]) saved = "en";
  setLanguage(saved);
}

